-- =====================================================================
-- Skema Sistem Absensi (sesuai ERD terbaru, 15 tabel)
-- DBMS: PostgreSQL 15+ (butuh SET NULL (kolom) dan partial unique index)
-- Waktu disimpan sebagai timestamptz (UTC), zona operasional Asia/Makassar
-- =====================================================================

BEGIN;

-- ---------------------------------------------------------------------
-- 1. Master pengguna dan organisasi
-- ---------------------------------------------------------------------
CREATE TABLE roles (
  id    SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code  VARCHAR(20) NOT NULL UNIQUE,   -- student, lecturer, staff, admin, superadmin
  name  VARCHAR(50) NOT NULL
);

CREATE TABLE departments (
  id    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code  VARCHAR(20)  NOT NULL UNIQUE,
  name  VARCHAR(150) NOT NULL
);

CREATE TABLE users (
  id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  role_id         SMALLINT     NOT NULL REFERENCES roles(id)       ON UPDATE CASCADE ON DELETE RESTRICT,
  department_id   INTEGER      NOT NULL REFERENCES departments(id) ON UPDATE CASCADE ON DELETE RESTRICT,
  identity_number VARCHAR(30)  NOT NULL UNIQUE,   -- NIM / NIP / NIDN
  full_name       VARCHAR(150) NOT NULL,
  email           VARCHAR(150) NOT NULL UNIQUE,
  phone           VARCHAR(20),
  password_hash   VARCHAR(255) NOT NULL,
  status          VARCHAR(20)  NOT NULL DEFAULT 'active',
  CONSTRAINT chk_users_status CHECK (status IN ('active', 'inactive', 'suspended')),
  CONSTRAINT chk_users_email  CHECK (position('@' IN email) > 1)
);

-- Spesialisasi pengguna (1 : 0..1)
CREATE TABLE students (
  user_id    BIGINT   PRIMARY KEY REFERENCES users(id) ON UPDATE CASCADE ON DELETE CASCADE,
  entry_year SMALLINT NOT NULL,
  CONSTRAINT chk_students_year CHECK (entry_year BETWEEN 2000 AND 2100)
);

CREATE TABLE employees (
  user_id        BIGINT PRIMARY KEY REFERENCES users(id) ON UPDATE CASCADE ON DELETE CASCADE,
  position_title VARCHAR(100)
);

-- ---------------------------------------------------------------------
-- 2. Kelas dan pendaftaran kelas
-- ---------------------------------------------------------------------
CREATE TABLE classes (
  id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  department_id INTEGER     NOT NULL REFERENCES departments(id) ON UPDATE CASCADE ON DELETE RESTRICT,
  name          VARCHAR(50) NOT NULL,
  CONSTRAINT uq_classes UNIQUE (department_id, name)
);

CREATE TABLE class_enrollments (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  class_id    INTEGER     NOT NULL REFERENCES classes(id)        ON UPDATE CASCADE ON DELETE RESTRICT,
  student_id  BIGINT      NOT NULL REFERENCES students(user_id)  ON UPDATE CASCADE ON DELETE RESTRICT,
  is_active   BOOLEAN     NOT NULL DEFAULT TRUE,
  enrolled_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT uq_class_enrollment UNIQUE (class_id, student_id)
);
-- satu mahasiswa hanya punya satu kelas aktif pada satu waktu
CREATE UNIQUE INDEX uq_enrollment_active_student ON class_enrollments (student_id) WHERE is_active;

-- ---------------------------------------------------------------------
-- 3. Lokasi dan sesi
-- ---------------------------------------------------------------------
CREATE TABLE locations (
  id        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name      VARCHAR(100) NOT NULL UNIQUE,
  latitude  NUMERIC(9,6) NOT NULL,
  longitude NUMERIC(9,6) NOT NULL,
  radius_m  INTEGER      NOT NULL DEFAULT 50,
  CONSTRAINT chk_loc_lat    CHECK (latitude  BETWEEN -90  AND 90),
  CONSTRAINT chk_loc_lng    CHECK (longitude BETWEEN -180 AND 180),
  CONSTRAINT chk_loc_radius CHECK (radius_m  BETWEEN 5 AND 5000)
);

CREATE TABLE sessions (
  id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title           VARCHAR(200) NOT NULL,
  location_id     INTEGER      NOT NULL REFERENCES locations(id) ON UPDATE CASCADE ON DELETE RESTRICT,
  created_by      BIGINT       NOT NULL REFERENCES users(id)     ON UPDATE CASCADE ON DELETE RESTRICT,
  checkin_open_at TIMESTAMPTZ  NOT NULL,
  start_at        TIMESTAMPTZ  NOT NULL,
  late_after      TIMESTAMPTZ  NOT NULL,
  end_at          TIMESTAMPTZ  NOT NULL,
  status          VARCHAR(20)  NOT NULL DEFAULT 'scheduled',
  require_qr      BOOLEAN      NOT NULL DEFAULT TRUE,
  require_gps     BOOLEAN      NOT NULL DEFAULT TRUE,
  CONSTRAINT chk_sessions_status CHECK (status IN ('scheduled', 'open', 'closed', 'cancelled')),
  CONSTRAINT chk_sessions_time   CHECK (
    checkin_open_at <= start_at AND start_at <= late_after AND late_after <= end_at AND end_at > start_at
  )
);

-- Snapshot peserta yang diharapkan hadir
CREATE TABLE session_participants (
  session_id BIGINT      NOT NULL REFERENCES sessions(id) ON UPDATE CASCADE ON DELETE CASCADE,
  user_id    BIGINT      NOT NULL REFERENCES users(id)    ON UPDATE CASCADE ON DELETE RESTRICT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  PRIMARY KEY (session_id, user_id)
);

CREATE TABLE qr_tokens (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  session_id BIGINT      NOT NULL REFERENCES sessions(id) ON UPDATE CASCADE ON DELETE CASCADE,
  token_hash CHAR(64)    NOT NULL UNIQUE,                 -- SHA-256, token asli tidak disimpan
  expires_at TIMESTAMPTZ NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT chk_qr_expiry CHECK (expires_at > created_at),
  -- target FK gabungan dari attendance_verifications
  CONSTRAINT uq_qr_id_session UNIQUE (id, session_id)
);

-- ---------------------------------------------------------------------
-- 4. Izin / sakit (satu pengajuan per peserta per sesi)
-- ---------------------------------------------------------------------
CREATE TABLE leave_requests (
  id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  session_id     BIGINT       NOT NULL,
  user_id        BIGINT       NOT NULL,
  leave_type     VARCHAR(20)  NOT NULL,
  reason         TEXT         NOT NULL,
  attachment_url VARCHAR(500),
  status         VARCHAR(20)  NOT NULL DEFAULT 'pending',
  reviewed_by    BIGINT       REFERENCES users(id) ON UPDATE CASCADE ON DELETE RESTRICT,
  reviewed_at    TIMESTAMPTZ,
  review_note    TEXT,
  -- pemohon harus peserta sesi tersebut
  CONSTRAINT fk_leave_participant FOREIGN KEY (session_id, user_id)
    REFERENCES session_participants (session_id, user_id) ON UPDATE CASCADE ON DELETE RESTRICT,
  CONSTRAINT uq_leave_session_user UNIQUE (session_id, user_id),
  -- target FK gabungan dari attendances
  CONSTRAINT uq_leave_id_session_user UNIQUE (id, session_id, user_id),
  CONSTRAINT chk_leave_type   CHECK (leave_type IN ('permission', 'sick')),
  CONSTRAINT chk_leave_status CHECK (status IN ('pending', 'approved', 'rejected', 'cancelled')),
  -- keputusan wajib mencatat peninjau dan waktu
  CONSTRAINT chk_leave_review CHECK (
    status IN ('pending', 'cancelled') OR (reviewed_by IS NOT NULL AND reviewed_at IS NOT NULL)
  ),
  -- tidak boleh menyetujui/menolak izin sendiri
  CONSTRAINT chk_leave_not_self CHECK (reviewed_by IS NULL OR reviewed_by <> user_id)
);

-- ---------------------------------------------------------------------
-- 5. Absensi dan verifikasi
-- ---------------------------------------------------------------------
CREATE TABLE attendances (
  id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  session_id       BIGINT       NOT NULL,
  user_id          BIGINT       NOT NULL,
  leave_request_id BIGINT,
  status           VARCHAR(20)  NOT NULL,
  check_in_at      TIMESTAMPTZ,
  check_out_at     TIMESTAMPTZ,
  corrected_by     BIGINT       REFERENCES users(id) ON UPDATE CASCADE ON DELETE RESTRICT,
  note             TEXT,
  -- hanya peserta terdaftar yang boleh punya absensi
  CONSTRAINT fk_att_participant FOREIGN KEY (session_id, user_id)
    REFERENCES session_participants (session_id, user_id) ON UPDATE CASCADE ON DELETE RESTRICT,
  -- izin yang menjadi dasar harus milik sesi dan pengguna yang sama (dilewati jika NULL)
  CONSTRAINT fk_att_leave FOREIGN KEY (leave_request_id, session_id, user_id)
    REFERENCES leave_requests (id, session_id, user_id) ON UPDATE CASCADE ON DELETE RESTRICT,
  -- tidak ada absensi ganda; satu izin hanya menjadi dasar satu absensi
  CONSTRAINT uq_att_session_user UNIQUE (session_id, user_id),
  CONSTRAINT uq_att_leave        UNIQUE (leave_request_id),
  -- target FK gabungan dari attendance_verifications
  CONSTRAINT uq_att_id_session   UNIQUE (id, session_id),
  CONSTRAINT chk_att_status   CHECK (status IN ('present', 'late', 'permission', 'sick', 'absent')),
  CONSTRAINT chk_att_checkout CHECK (
    check_out_at IS NULL OR (check_in_at IS NOT NULL AND check_out_at >= check_in_at)
  ),
  CONSTRAINT chk_att_checkin_status CHECK (status IN ('present', 'late') OR check_in_at IS NULL),
  -- tautan izin hanya untuk status permission/sick
  CONSTRAINT chk_att_leave_link CHECK (leave_request_id IS NULL OR status IN ('permission', 'sick')),
  -- status permission/sick wajib punya izin, kecuali koreksi manual
  CONSTRAINT chk_att_leave_required CHECK (
    status NOT IN ('permission', 'sick') OR leave_request_id IS NOT NULL OR corrected_by IS NOT NULL
  ),
  -- koreksi manual wajib punya alasan
  CONSTRAINT chk_att_correction_note CHECK (corrected_by IS NULL OR note IS NOT NULL)
);

CREATE TABLE attendance_verifications (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  attendance_id BIGINT       NOT NULL,
  session_id    BIGINT       NOT NULL REFERENCES sessions(id) ON UPDATE CASCADE ON DELETE RESTRICT,
  qr_token_id   BIGINT,
  event_type    VARCHAR(20)  NOT NULL,
  method        VARCHAR(10)  NOT NULL,
  is_passed     BOOLEAN      NOT NULL,
  latitude      NUMERIC(9,6),
  longitude     NUMERIC(9,6),
  distance_m    NUMERIC(8,2),
  created_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
  -- absensi harus berada di sesi yang sama dengan verifikasi
  CONSTRAINT fk_verif_attendance FOREIGN KEY (attendance_id, session_id)
    REFERENCES attendances (id, session_id) ON UPDATE CASCADE ON DELETE CASCADE,
  -- token QR harus milik sesi yang sama (dilewati jika NULL)
  CONSTRAINT fk_verif_qr FOREIGN KEY (qr_token_id, session_id)
    REFERENCES qr_tokens (id, session_id) ON UPDATE CASCADE ON DELETE RESTRICT,
  CONSTRAINT chk_verif_event  CHECK (event_type IN ('check_in', 'check_out')),
  CONSTRAINT chk_verif_method CHECK (method IN ('qr', 'gps')),
  CONSTRAINT chk_verif_lat    CHECK (latitude   IS NULL OR latitude  BETWEEN -90  AND 90),
  CONSTRAINT chk_verif_lng    CHECK (longitude  IS NULL OR longitude BETWEEN -180 AND 180),
  CONSTRAINT chk_verif_dist   CHECK (distance_m IS NULL OR distance_m >= 0),
  CONSTRAINT chk_verif_qr     CHECK (qr_token_id IS NULL OR method = 'qr')
);
-- percobaan gagal boleh berulang; yang lolos maksimal satu per event dan metode
CREATE UNIQUE INDEX uq_verif_passed
  ON attendance_verifications (attendance_id, event_type, method) WHERE is_passed;

-- ---------------------------------------------------------------------
-- 6. Audit log
-- ---------------------------------------------------------------------
CREATE TABLE audit_logs (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id     BIGINT      REFERENCES users(id) ON UPDATE CASCADE ON DELETE RESTRICT,
  action      VARCHAR(50) NOT NULL,
  entity_type VARCHAR(50) NOT NULL,
  entity_id   BIGINT,
  created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- ---------------------------------------------------------------------
-- 7. Index
-- ---------------------------------------------------------------------
CREATE INDEX idx_users_role_status     ON users (role_id, status);
CREATE INDEX idx_users_department      ON users (department_id);
CREATE INDEX idx_classes_department    ON classes (department_id);
CREATE INDEX idx_enrollments_class     ON class_enrollments (class_id) WHERE is_active;

CREATE INDEX idx_sessions_start        ON sessions (start_at);
CREATE INDEX idx_sessions_active       ON sessions (start_at) WHERE status IN ('scheduled', 'open');
CREATE INDEX idx_sessions_creator      ON sessions (created_by);
CREATE INDEX idx_participants_user     ON session_participants (user_id);
CREATE INDEX idx_qr_session_expiry     ON qr_tokens (session_id, expires_at DESC);

CREATE INDEX idx_leave_pending         ON leave_requests (session_id) WHERE status = 'pending';
CREATE INDEX idx_leave_reviewer        ON leave_requests (reviewed_by, reviewed_at DESC) WHERE reviewed_by IS NOT NULL;
CREATE INDEX idx_leave_user            ON leave_requests (user_id);

CREATE INDEX idx_att_user_session      ON attendances (user_id, session_id);
CREATE INDEX idx_att_session_status    ON attendances (session_id, status);
CREATE INDEX idx_att_checkin           ON attendances (check_in_at);

CREATE INDEX idx_verif_attendance      ON attendance_verifications (attendance_id);
CREATE INDEX idx_verif_session         ON attendance_verifications (session_id);
CREATE INDEX idx_verif_qr              ON attendance_verifications (qr_token_id) WHERE qr_token_id IS NOT NULL;

CREATE INDEX idx_audit_user_time       ON audit_logs (user_id, created_at DESC);
CREATE INDEX idx_audit_entity          ON audit_logs (entity_type, entity_id);
CREATE INDEX idx_audit_time            ON audit_logs (created_at DESC);

-- ---------------------------------------------------------------------
-- 8. Trigger: validasi status absensi terhadap jadwal dan izin
--    (CHECK tidak bisa lintas tabel, jadi memakai trigger)
--    Koreksi manual (corrected_by terisi) dilewati.
-- ---------------------------------------------------------------------
CREATE FUNCTION validate_attendance() RETURNS trigger AS $$
DECLARE
  s       sessions%ROWTYPE;
  l_stat  VARCHAR(20);
BEGIN
  IF NEW.corrected_by IS NOT NULL THEN
    RETURN NEW;
  END IF;

  SELECT * INTO s FROM sessions WHERE id = NEW.session_id;

  IF NEW.check_in_at IS NOT NULL THEN
    IF s.status <> 'open' THEN
      RAISE EXCEPTION 'check-in ditolak: sesi % tidak sedang dibuka', NEW.session_id;
    END IF;
    IF NEW.check_in_at < s.checkin_open_at OR NEW.check_in_at > s.end_at THEN
      RAISE EXCEPTION 'check-in ditolak: di luar jendela sesi %', NEW.session_id;
    END IF;
    IF NEW.status = 'late' AND NEW.check_in_at <= s.late_after THEN
      RAISE EXCEPTION 'status late tidak valid: check-in belum melewati batas toleransi';
    END IF;
    IF NEW.status = 'present' AND NEW.check_in_at > s.late_after THEN
      RAISE EXCEPTION 'status present tidak valid: check-in sudah melewati batas toleransi';
    END IF;
  END IF;

  IF NEW.leave_request_id IS NOT NULL THEN
    SELECT status INTO l_stat FROM leave_requests WHERE id = NEW.leave_request_id;
    IF l_stat <> 'approved' THEN
      RAISE EXCEPTION 'izin % belum disetujui', NEW.leave_request_id;
    END IF;
    IF (NEW.status = 'sick' AND (SELECT leave_type FROM leave_requests WHERE id = NEW.leave_request_id) <> 'sick')
    OR (NEW.status = 'permission' AND (SELECT leave_type FROM leave_requests WHERE id = NEW.leave_request_id) <> 'permission') THEN
      RAISE EXCEPTION 'status absensi tidak cocok dengan jenis izin';
    END IF;
  END IF;

  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_att_validate
  BEFORE INSERT OR UPDATE OF status, check_in_at, leave_request_id, corrected_by ON attendances
  FOR EACH ROW EXECUTE FUNCTION validate_attendance();

-- ---------------------------------------------------------------------
-- 9. Trigger: audit_logs hanya boleh ditambah (append-only)
-- ---------------------------------------------------------------------
CREATE FUNCTION audit_logs_immutable() RETURNS trigger AS $$
BEGIN
  RAISE EXCEPTION 'audit_logs bersifat append-only (% ditolak)', TG_OP;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_audit_no_change
  BEFORE UPDATE OR DELETE ON audit_logs
  FOR EACH ROW EXECUTE FUNCTION audit_logs_immutable();

CREATE TRIGGER trg_audit_no_truncate
  BEFORE TRUNCATE ON audit_logs
  FOR EACH STATEMENT EXECUTE FUNCTION audit_logs_immutable();

